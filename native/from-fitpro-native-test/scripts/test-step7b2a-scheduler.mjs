/** Dependency-free structural regression check of the installed native scheduler smoke test. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const file = (path) => readFileSync(resolve(root,path),'utf8');
const worker=file('src/ingestion/background-scheduler-diagnostic.ts');
const panel=file('src/ingestion/background-scheduler-diagnostic-panel.tsx');
const screen=file('app/activities.tsx');
const session=file('src/auth/session.tsx');
const entry=file('index.js');
const config=JSON.parse(file('app.json')).expo;
const pkg=JSON.parse(file('package.json'));
assert.equal(pkg.main,'./index.js');
assert(entry.includes('background-scheduler-diagnostic') && entry.indexOf('background-scheduler-diagnostic') < entry.indexOf("expo-router/entry"));
assert(worker.includes('TaskManager.defineTask(') && worker.includes('BackgroundTask.registerTaskAsync('));
assert(worker.includes('BackgroundTask.unregisterTaskAsync('));
assert(worker.includes('SecureStore.getItemAsync(DIAGNOSTIC_ENABLED)'));
assert(worker.includes("consent !== 'accepted:v1'"));
assert(!/healthkit|health-connect|submitHealthActivity|ingestActivity|fetch\(|axios|base44\.entities/i.test(worker));
assert(panel.includes('NO health data will be read or uploaded.') && panel.includes('Stop scheduler diagnostic'));
assert(screen.includes('<BackgroundSchedulerDiagnosticPanel provider={adapter.id}'));
assert.equal(session.split('await clearBackgroundSchedulerDiagnostic();').length-1,3);
assert(config.plugins.some((p)=>Array.isArray(p)&&p[0]==='@kingstinct/react-native-healthkit'&&p[1].background===true));
assert(config.android.permissions.includes('android.permission.health.READ_HEALTH_DATA_IN_BACKGROUND'));
assert(!worker.includes('readActivities('));
console.log('PASS: Global Expo background task defined before Expo Router; native permissions declared; separate scheduler test requires opt-in.');
console.log('PASS: Diagnostic has no HealthKit/Health Connect reads, uploads, network calls or backend changes.');
console.log('PASS: Sign-out/new login/consent withdrawal cancel registered task and clear diagnostic state.');
