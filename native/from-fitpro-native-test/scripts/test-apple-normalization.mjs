import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';

const source = readFileSync(new URL('../src/health/apple-normalize.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const scope = { exports: {} };
vm.runInNewContext(compiled, scope);
const { toMiles, toSeconds, resolveWorkoutDistance, resolveWorkoutDuration, beatsPerMinute, sanitizeRoute } = scope.exports;
assert(Math.abs(toMiles(1609.344, 'm') - 1) < 1e-9);
assert(Math.abs(toMiles(5, 'km') - 3.10685596) < 0.0001);
assert.equal(toMiles(1, 'unknown'), null);
assert.equal(toSeconds(30, 'min'), 1800);
assert.equal(toSeconds(10, 'unsupported'), null);
assert.equal(toMiles(1609.344, 'meters'), 1);
assert.equal(toMiles(1, 'mile'), 1);
assert.equal(toSeconds(45, 'seconds'), 45);
assert.equal(resolveWorkoutDistance(undefined, { quantity: 1609.344, unit: 'm' }), 1);
assert.equal(resolveWorkoutDistance({ quantity: 0, unit: 'm' }, { quantity: 3218.688, unit: 'm' }), 2);
assert.equal(resolveWorkoutDistance({ quantity: 1, unit: 'mi' }, { quantity: 3218.688, unit: 'm' }), 1);
assert.equal(resolveWorkoutDistance(undefined, undefined), null);
const t0 = new Date('2026-11-12T10:00:00.000Z');
const t1 = new Date('2026-11-12T10:20:00.000Z');
assert.equal(resolveWorkoutDuration({ quantity: 1100, unit: 's' }, t0, t1).seconds, 1100);
assert.equal(resolveWorkoutDuration({ quantity: 1100, unit: 's' }, t0, t1).fromElapsedTime, false);
assert.equal(resolveWorkoutDuration(undefined, t0, t1).seconds, 1200);
assert.equal(resolveWorkoutDuration(undefined, t0, t1).fromElapsedTime, true);
assert.equal(resolveWorkoutDuration(undefined, t1, t0).seconds, null);
assert.equal(beatsPerMinute(2, 'count/s'), 120);
assert.equal(beatsPerMinute(75, 'count/min'), 75);
assert.equal(beatsPerMinute(42, 'bad-unit'), undefined);
const locations = Array.from({ length: 8000 }, (_, i) => ({ latitude: 37 + i * 0.00001, longitude: -122 + i * 0.00001 }));
const points = sanitizeRoute(locations);
assert.equal(points.length, 5000);
assert.equal(points[0].lat, locations[0].latitude);
assert.equal(points.at(-1).lng, locations.at(-1).longitude);
assert.equal(sanitizeRoute([{ latitude: 111, longitude: 20 }, { latitude: 30, longitude: -90 }]).length, 1);
console.log('PASS: workout distance-statistics fallback, duration fallback diagnostics, HR units, route validation and 5000-point cap.');
