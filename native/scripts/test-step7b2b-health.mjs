/** Purely static safety/integration checks. Real OS reads require dev builds/devices. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const read = (p) => readFileSync(resolve(root,p),'utf8');
const code = read('src/ingestion/background-health-read-diagnostic.ts');
const panel = read('src/ingestion/background-health-read-diagnostic-panel.tsx');
const entry = read('index.js');
const session = read('src/auth/session.tsx');
const activities = read('app/activities.tsx');
const config = JSON.parse(read('app.json')).expo;
assert(entry.includes("import './src/ingestion/background-health-read-diagnostic';"));
assert(entry.indexOf("background-health-read-diagnostic';") < entry.indexOf("expo-router/entry';"));
assert(code.includes('TaskManager.defineTask(FITPRO_HEALTH_READ_TASK'));
assert(code.includes('BackgroundTask.registerTaskAsync(FITPRO_HEALTH_READ_TASK'));
assert(code.includes('BackgroundTask.unregisterTaskAsync(FITPRO_HEALTH_READ_TASK'));
assert(code.includes('BackgroundAccessPermission'));
assert(code.includes('hc.getGrantedPermissions()') && code.includes('hc.requestPermission(['));
assert(code.includes('hk.requestAuthorization({ toRead: [hk.WorkoutTypeIdentifier] })'));
assert(code.includes('hk.configureBackgroundTypes(['));
assert(code.includes('hk.clearBackgroundTypes()'));
assert(code.includes('hk.queryWorkoutSamples({') && code.includes("hc.readRecords('ExerciseSession'") && code.includes("hc.readRecords('Distance'"));
assert(code.includes('MAX_SAMPLES = 20') && code.includes('consent !== \'accepted:v1\'') && code.includes('nextToken !== token'));
assert(!/\bfetch\s*\(|axios|ingestActivity|submitHealthActivity|base44\.entities|insertRecords|deleteRecords|saveWorkoutSample|writeExerciseRoute/i.test(code));
assert(!/externalId|routeName|points|heartRate|avgHr|uuid|metadata\??\.dataOrigin/.test(code));
assert(panel.includes('NO BACKGROUND UPLOADS') && panel.includes('Enable background health read test'));
assert(activities.includes('<BackgroundHealthReadDiagnosticPanel provider={adapter.id}'));
assert.equal(session.split('await clearBackgroundHealthReadDiagnostic();').length-1,3);
assert(config.android.permissions.includes('android.permission.health.READ_HEALTH_DATA_IN_BACKGROUND'));
assert(config.plugins.some(p=>Array.isArray(p)&&p[0]==='@kingstinct/react-native-healthkit'&&p[1].background===true));
console.log('PASS: Separate opt-in native health read diagnostic; OS permissions requested in foreground only.');
console.log('PASS: Headless worker uses bounded health reads and stores no workout identities, route, or samples.');
console.log('PASS: No backend calls, uploads, health writes or automatic retry loop.');
console.log('PASS: Opt-out/new login/sign-out/consent withdrawal clear diagnostic state.');
